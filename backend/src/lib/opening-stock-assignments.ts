export type OpeningStockAssignment = {
  variantSku: string;
  warehouseCode: string;
  zone: string;
  shelf: string;
  bin: string;
  qty: number;
};

export function parseOpeningStockAssignments(): OpeningStockAssignment[] {
  return OPENING_STOCK_ASSIGNMENTS_RAW.split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => {
      const [variantSku, warehouseCode, zone, shelf, bin] = line.split("|");
      if (!variantSku || !warehouseCode || !zone || !shelf || !bin) {
        throw new Error(`Bad assignment line: ${line}`);
      }
      return {
        variantSku,
        warehouseCode,
        zone,
        shelf,
        bin,
        qty: OPENING_STOCK_QTY,
      };
    });
}

/** Shelf aliases — UI may show S017 while layout uses S17. */
export function shelfCandidates(shelf: string): string[] {
  const out = new Set<string>([shelf]);
  const m = shelf.match(/^S0*(\d+)$/i);
  if (m) {
    const n = parseInt(m[1]!, 10);
    out.add(`S${n}`);
    out.add(`S${String(n).padStart(2, "0")}`);
    out.add(`S${String(n).padStart(3, "0")}`);
  }
  return [...out];
}

/** Bin label aliases — 01 vs 1. */
export function binCandidates(bin: string): string[] {
  const out = new Set<string>([bin]);
  const n = parseInt(bin, 10);
  if (Number.isFinite(n)) {
    out.add(String(n));
    out.add(String(n).padStart(2, "0"));
  }
  return [...out];
}
